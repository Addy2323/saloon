// CSV/Excel export — generates a .csv file (opens in Excel)
// PDF export — uses the browser's print dialog on a formatted HTML page

export function exportCSV(filename: string, headers: string[], rows: (string | number)[][]) {
  const escape = (val: string | number) => {
    const s = String(val ?? '');
    if (s.includes(',') || s.includes('"') || s.includes('\n')) {
      return `"${s.replace(/"/g, '""')}"`;
    }
    return s;
  };

  const csv = [headers, ...rows].map((row) => row.map(escape).join(',')).join('\n');
  const blob = new Blob(['\ufeff' + csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename + '.csv';
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function exportPDF(title: string, sections: { heading: string; headers: string[]; rows: (string | number)[][] }[], summary?: { label: string; value: string }[]) {
  const printWindow = window.open('', '_blank', 'width=900,height=700');
  if (!printWindow) return;

  const buildTable = (section: { heading: string; headers: string[]; rows: (string | number)[][] }) => {
    const head = section.headers.map((h) => `<th>${h}</th>`).join('');
    const body = section.rows
      .map(
        (row) =>
          `<tr>${row.map((c) => `<td>${c}</td>`).join('')}</tr>`
      )
      .join('');
    return `
      <h2>${section.heading}</h2>
      <table>
        <thead><tr>${head}</tr></thead>
        <tbody>${body}</tbody>
      </table>
    `;
  };

  const summaryHtml = summary
    ? `<div class="summary">${summary
        .map((s) => `<div class="sum-item"><span>${s.label}</span><strong>${s.value}</strong></div>`)
        .join('')}</div>`
    : '';

  const html = `
<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>${title}</title>
<style>
  * { font-family: 'Segoe UI', Arial, sans-serif; }
  body { margin: 32px; color: #333; }
  .header { text-align: center; margin-bottom: 24px; padding-bottom: 16px; border-bottom: 3px solid #e04b72; }
  .header h1 { font-size: 24px; color: #b1224b; margin: 0; }
  .header p { font-size: 12px; color: #888; margin: 4px 0 0; }
  h2 { font-size: 16px; color: #5b554e; margin: 24px 0 8px; }
  .summary { display: flex; flex-wrap: wrap; gap: 16px; margin: 16px 0; }
  .sum-item { background: #fdf2f4; padding: 12px 20px; border-radius: 8px; min-width: 180px; }
  .sum-item span { display: block; font-size: 11px; color: #877f74; }
  .sum-item strong { font-size: 16px; color: #b1224b; }
  table { width: 100%; border-collapse: collapse; margin-bottom: 16px; font-size: 13px; }
  th { background: #fce7eb; color: #b1224b; padding: 8px 12px; text-align: left; font-weight: 600; }
  td { padding: 8px 12px; border-bottom: 1px solid #eee; }
  tr:nth-child(even) td { background: #fafafa; }
  .footer { margin-top: 32px; text-align: center; font-size: 10px; color: #aaa; border-top: 1px solid #eee; padding-top: 12px; }
  @media print { body { margin: 16px; } }
</style>
</head>
<body>
  <div class="header">
    <h1>Lucentia Beauty & Salon</h1>
    <p>${title} — ${new Date().toLocaleDateString('en-GB')}</p>
  </div>
  ${summaryHtml}
  ${sections.map(buildTable).join('')}
  <div class="footer">Generated by Lucentia Beauty & Salon Management System</div>
  <script>window.onload = () => { window.print(); }</script>
</body>
</html>`;

  printWindow.document.open();
  printWindow.document.write(html);
  printWindow.document.close();
}
